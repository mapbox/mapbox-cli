//! `mapbox generate-skills`: this CLI's own command surface, written out as
//! an Agent Skill.
//!
//! An agent handed a CLI it has never seen either runs `--help` sixty times
//! or guesses. `--schema` fixed the second half of that — the facts are
//! available as data — but an agent still has to know the command exists
//! before it can ask, and a schema says nothing about the parts that are true
//! of every command: where the token comes from, which stream the result
//! arrives on, what an error looks like.
//!
//! So this writes both halves down, once, into the directory the agent
//! already reads: a `SKILL.md` index with the cross-cutting rules, and one
//! reference page per service listing every command with its arguments, its
//! request and a worked example.
//!
//! # Where the content comes from
//!
//! [`crate::schema::build`] — the same walk `--schema` publishes, over the
//! same built [`Command`] tree, filtered by the same
//! [`crate::spec::Operation::is_exposed`]. Nothing here re-reads the OpenAPI
//! specs, and nothing here decides what is a command.
//!
//! That is the whole design. A second walk of the specs would be a second
//! opinion about what this CLI does, and the two would drift on the first
//! sync — advertising an operation the CLI withholds, which sends an agent to
//! a command that answers exactly as a typo does. Rendering the schema
//! instead makes three of the four guarantees the issue asks for structural
//! rather than tested: a withheld, disabled or liveness operation is absent
//! because it was never in the schema, and a command that exists is present
//! because `every_command_in_the_tree_is_described` fails the build
//! otherwise. The tests below still assert all four, because a guarantee
//! nothing checks is a comment.
//!
//! # Determinism
//!
//! Two runs against one build produce byte-identical trees, so a generated
//! skill can be committed and a diff means something changed. That rules out
//! timestamps, hostnames, absolute paths and hash-map iteration order: every
//! collection here is sorted explicitly, and line endings are written as `\n`
//! rather than the platform's.
//!
//! # Writing
//!
//! The skill directory is replaced, not merged — it is generated output, and
//! a half-updated one is worse than either version. So it is built in a
//! hidden sibling directory and renamed into place, and a directory holding
//! anything this command did not write is refused rather than overwritten.

