    /// A command that is its own service must not have its one sentence
    /// printed three times.
    #[test]
    fn a_single_command_service_says_its_summary_once() {
        let (_, _, files) = generated();

        for service in [COMMAND, tilesets_cli::COMMAND] {
            let page = files
                .iter()
                .find(|file| file.path == Path::new("references").join(format!("{service}.md")))
                .unwrap_or_else(|| panic!("{service} has a reference page"));

            // The page heading, then straight to the command — no service
            // intro repeating what the command's own block says.
            let summary_line = page.contents.lines().find(|line| {
                line.starts_with("Write Agent Skills") || line.starts_with("Proxy commands")
            });
            if let Some(summary) = summary_line {
                assert_eq!(
                    page.contents.matches(summary).count(),
                    1,
                    "{service}.md repeats {summary:?}"
                );
            }
        }

        // A service with real operations still gets its own intro, which is a
        // different sentence from any command's.
        let styles = files
            .iter()
            .find(|file| file.path == Path::new("references").join("styles.md"))
            .expect("styles has a reference page");
        assert!(
            styles.contents.contains("Mapbox Styles API"),
            "styles.md lost its service intro"
        );
    }

    /// A directory holding someone else's file is refused, named, and left
    /// alone until `--force`.
    #[test]
    fn a_directory_we_did_not_write_is_refused_by_name() {
        let root = std::env::temp_dir().join("mapbox-cli-generate-skills-stranger");
        let skill = root.join(SKILL_NAME);
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(skill.join("references")).expect("create the skill dir");

        let destination = Destination {
            root: root.clone(),
            source: None,
        };
        let files = vec![GeneratedFile {
            path: PathBuf::from("SKILL.md"),
            contents: format!("{}\n", Header::new(None).comment()),
        }];

        // Ours: every file carries the marker.
        fs::write(
            skill.join("SKILL.md"),
            format!("{}\n", Header::new(None).comment()),
        )
        .expect("write a generated file");
        assert!(strangers(&skill).unwrap().is_empty());
        assert!(plan(destination.clone(), files.clone(), false).is_ok());

        // And not ours the moment anything else is in there, however deep.
        fs::write(skill.join("references").join("notes.md"), "mine\n").expect("write a stranger");
        assert_eq!(
            strangers(&skill).unwrap(),
            vec![PathBuf::from("references").join("notes.md")]
        );

        let err =
            plan(destination.clone(), files.clone(), false).expect_err("a stranger is present");
        let message = err.to_string();
        assert!(message.contains("notes.md"), "{message}");
        assert!(message.contains("--force"), "{message}");

        assert!(
            plan(destination, files, true).is_ok(),
            "--force has to get past it"
        );

        let _ = fs::remove_dir_all(&root);
    }

    /// A write replaces the directory whole: a file we no longer generate has
    /// to go, or it outlives the command that made it forever.
    #[test]
    fn a_write_replaces_the_directory_rather_than_merging_into_it() {
        let root = std::env::temp_dir().join("mapbox-cli-generate-skills-replace");
        let _ = fs::remove_dir_all(&root);

        let marker = format!("{}\n", Header::new(None).comment());
        let stale = Plan {
            destination: Destination {
                root: root.clone(),
                source: None,
            },
            files: vec![
                GeneratedFile {
                    path: PathBuf::from("SKILL.md"),
                    contents: marker.clone(),
                },
                GeneratedFile {
                    path: PathBuf::from("references").join("gone.md"),
                    contents: marker.clone(),
                },
            ],
        };
        apply(&stale).expect("first write");
        assert!(root.join(SKILL_NAME).join("references/gone.md").exists());

        let fresh = Plan {
            destination: stale.destination,
            files: vec![GeneratedFile {
                path: PathBuf::from("SKILL.md"),
                contents: marker,
            }],
        };
        apply(&fresh).expect("second write");
        assert!(root.join(SKILL_NAME).join("SKILL.md").exists());
        assert!(
            !root.join(SKILL_NAME).join("references/gone.md").exists(),
            "a file we stopped generating survived"
        );
        // Neither working directory is left behind.
        assert!(!root.join(STAGING_DIR).exists());
        assert!(!root.join(ARCHIVE_DIR).exists());

        let _ = fs::remove_dir_all(&root);
    }
