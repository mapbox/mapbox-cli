/// Subcommand users type: `mapbox generate-skills`.
pub const COMMAND: &str = "generate-skills";

/// The directory written under each destination, and the skill's `name` in
/// its own frontmatter — the two have to match for an agent to load it.
const SKILL_NAME: &str = "mapbox-cli";

/// The sentence that says a file is ours.
///
/// Kept short and kept whole: it is matched as a literal in the first
/// kibibyte of every file under the skill directory, and that match is the
/// only thing standing between a regenerate and someone else's work. See
/// [`strangers`].
const GENERATED_MARKER: &str = "Generated by `mapbox generate-skills`";

/// How far into a file the marker has to appear. Long enough for YAML
/// frontmatter and a heading to precede it, short enough that a stray
/// occurrence deep inside a hand-written document is not mistaken for one.
const MARKER_WINDOW: usize = 1024;

const SERVICE_ARG: &str = "service";
const FORCE_ARG: &str = "force";

/// Built beside the destination and renamed in, so a crash cannot leave a
/// half-written skill where an agent will read it.
const STAGING_DIR: &str = ".mapbox-cli.generating";

/// Where the directory being replaced waits until the new one is in place.
const ARCHIVE_DIR: &str = ".mapbox-cli.replaced";

const DRY_RUN_HELP: &str = "List the files this would write, then exit without writing them";

pub fn command() -> Command {
    Command::new(COMMAND)
        .about("Write Agent Skills describing this CLI's own commands, for a coding agent to read")
        .long_about(format!(
            "Write Agent Skills describing this CLI's own commands.\n\n\
             Produces a `{SKILL_NAME}` skill directory — a SKILL.md index, an \
             AGENTS.md carrying the same prose, and one reference page per command group \
             listing every command with its arguments, the request it makes and a \
             worked example.\n\n\
             The content is derived from the command tree this binary built, not from \
             the API specs, so it describes exactly the commands that exist: an \
             operation this CLI withholds, disables or treats as a liveness probe is \
             absent from the skill for the same reason it is absent from `--help`.\n\n\
             Two runs of one binary write byte-identical files, so the result can be \
             committed and a diff means the CLI changed. Nothing here reaches the \
             network, and no token is needed.\n\n\
             With no flags, writes into the project directory of every agent whose \
             home directory is present."
        ))
        .args(skill_dest::args())
        .arg(
            Arg::new(SERVICE_ARG)
                .long(SERVICE_ARG)
                .value_name("SERVICE")
                .action(ArgAction::Append)
                .help("Describe only this command group, repeatable. Defaults to all of them"),
        )
        .arg(
            Arg::new(FORCE_ARG)
                .long(FORCE_ARG)
                .action(ArgAction::SetTrue)
                .help("Replace a skill directory holding files this command did not write"),
        )
        .arg(executor::dry_run_arg(DRY_RUN_HELP))
}

pub fn run(app: &Command, specs: &[ServiceSpec], matches: &ArgMatches, mode: Mode) -> Result<()> {
    let schema = schema::build(app, specs, &[]);
    let header = Header::new(requested_services(&schema, matches)?);
    let files = render(app, &schema, &header);

    let homes = AgentHomes::from_env();
    let destinations = skill_dest::from_matches(matches, &homes, true)?;
    let force = matches.get_flag(FORCE_ARG);

    // Every destination is checked before any of them is written: a refusal
    // on the second one, after the first has been replaced, leaves the caller
    // having to work out which half happened.
    let plans: Vec<Plan> = destinations
        .into_iter()
        .map(|destination| plan(destination, files.clone(), force))
        .collect::<Result<_>>()?;

    let dry_run = executor::wants_dry_run(matches);
    if !dry_run {
        for plan in &plans {
            apply(plan)?;
        }
    }

    report(mode, &plans, dry_run)
}

/// The services to describe, or `None` for all of them.
///
/// An unrecognised name is an error naming the alternatives rather than a
/// silent no-op: `--service style` is a typo, and writing a skill that
/// describes nothing is a worse answer to it than refusing.
fn requested_services(schema: &Schema, matches: &ArgMatches) -> Result<Option<Vec<String>>> {
    let requested: Vec<&String> = matches
        .get_many::<String>(SERVICE_ARG)
        .into_iter()
        .flatten()
        .collect();
    if requested.is_empty() {
        return Ok(None);
    }

    let known: BTreeSet<&str> = schema
        .commands
        .iter()
        .map(|entry| entry.service.as_str())
        .collect();

    let mut wanted: Vec<String> = vec![];
    for name in requested {
        if !known.contains(name.as_str()) {
            return Err(CliError::new(
                "unknown_service",
                format!(
                    "`{name}` is not a command group of this CLI. Pick from: {}.",
                    known.iter().copied().collect::<Vec<&str>>().join(", ")
                ),
            )
            .into());
        }
        if !wanted.iter().any(|seen| seen == name) {
            wanted.push(name.clone());
        }
    }
    wanted.sort();
    Ok(Some(wanted))
}

/// What every generated file says about the build that wrote it.
///
/// Three facts, and deliberately only three: the CLI version, which fixes the
/// hand-written commands and the output contract; the spec digest, which
/// fixes the generated ones; and the openapi-specs commit, when the build
/// could work one out. A reader comparing the digest against a fresh
/// `mapbox generate-skills --dry-run` learns whether the skill is stale,
/// which is the only question a header can usefully answer.
///
/// No timestamp, no hostname, no path. Each would make two runs of one binary
/// differ, which is the property that lets a generated skill be committed.
struct Header {
    cli_version: &'static str,
    spec_digest: String,
    /// From `build.rs`, which reads the commit `openapi/` was derived from
    /// out of a maintainer-only manifest file. Absent
    /// whenever that file is missing or malformed, which is why the digest
    /// above is the primary signal and this is the convenience. Says nothing
    /// about a `custom-openapi/` spec, which the digest also covers — including
    /// `custom-openapi/statistics/`, folded in by hand in `spec_digest()`
    /// since it's `include_str!`'d directly by `account_usage.rs` rather
    /// than reachable through `CUSTOM_SPEC_ENTRIES`.
    spec_commit: Option<&'static str>,
    /// Set only when `--service` narrowed the skill, since a reader otherwise
    /// has no way to tell a partial skill from a complete one.
    services: Option<Vec<String>>,
}

impl Header {
    fn new(services: Option<Vec<String>>) -> Self {
        Header {
            cli_version: env!("CARGO_PKG_VERSION"),
            spec_digest: spec_digest(),
            spec_commit: option_env!("MAPBOX_SPEC_COMMIT").map(str::trim),
            services,
        }
    }

    fn comment(&self) -> String {
        let specs = match self.spec_commit {
            Some(commit) if !commit.is_empty() => {
                format!(
                    "openapi-specs {commit}, content digest {} (also covers custom-openapi)",
                    self.spec_digest
                )
            }
            _ => format!(
                "content digest {} (openapi-specs + custom-openapi)",
                self.spec_digest
            ),
        };

        let mut lines = vec![
            format!("<!-- {GENERATED_MARKER} — do not edit; regenerate instead."),
            format!("     {SKILL_NAME} {}", self.cli_version),
            format!("     {specs}"),
        ];
        if let Some(services) = &self.services {
            lines.push(format!("     command groups: {}", services.join(", ")));
        }
        lines.push("-->".to_string());
        lines.join("\n")
    }

    /// Whether the requested services include this one. Everything is
    /// included when `--service` said nothing.
    fn includes(&self, service: &str) -> bool {
        self.services
            .as_ref()
            .is_none_or(|wanted| wanted.iter().any(|name| name == service))
    }
}

/// Whether a file's first kibibyte claims this command wrote it.
fn marker_in(contents: &[u8]) -> bool {
    let head = &contents[..contents.len().min(MARKER_WINDOW)];
    head.windows(GENERATED_MARKER.len())
        .any(|window| window == GENERATED_MARKER.as_bytes())
}

/// A short digest of the OpenAPI content this binary was compiled against.
///
/// The specs are embedded by `include_str!`, so this is the content of the
/// build rather than of the working tree — which is the honest thing for a
/// generated document to record, and the reason it is preferred over the git
/// commit above. Sorted by service name and separated by NUL, so the digest
/// depends on the specs and not on the order they happen to be declared in,
/// and so no rename can produce the same bytes as some other pairing.
fn spec_digest() -> String {
    // The effective list, so a hand-authored spec under `custom-openapi/`
    // moves the digest the same way an openapi-specs change does. Plus
    // `statistics`, `include_str!`'d directly by `account_usage.rs` rather
    // than reachable through `effective_spec_entries()` — without this line
    // added by hand, editing that one spec would leave every generated
    // skill's digest unchanged.
    let compiled_in = crate::spec::effective_spec_entries();
    let mut entries: Vec<(&str, &str)> = compiled_in
        .iter()
        .map(|entry| (entry.name, entry.yaml))
        .chain(std::iter::once(("statistics", crate::account_usage::SPEC)))
        .collect();
    entries.sort_unstable_by_key(|(name, _)| *name);

    let mut hasher = Sha256::new();
    for (name, yaml) in entries {
        hasher.update(name.as_bytes());
        hasher.update([0]);
        hasher.update(yaml.as_bytes());
        hasher.update([0]);
    }

    hasher
        .finalize()
        .iter()
        .take(6)
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// One file, and where it goes relative to the skill directory.
#[derive(Clone, Debug, PartialEq, Eq)]
struct GeneratedFile {
    path: PathBuf,
    contents: String,
}

/// One destination's worth of work, decided but not yet done.
#[derive(Debug)]
struct Plan {
    destination: Destination,
    files: Vec<GeneratedFile>,
}

impl Plan {
    /// The directory the files go in — the destination's skills root plus the
    /// skill's own name.
    fn skill_dir(&self) -> PathBuf {
        self.destination.root.join(SKILL_NAME)
    }
}

/// Every service that has commands to describe, sorted, each with its
/// commands sorted.
///
/// A `BTreeMap` rather than a `HashMap` because the order is output: two runs
/// of one binary have to write the same bytes, and hash iteration order is
/// not a promise.
fn by_service<'a>(schema: &'a Schema, header: &Header) -> BTreeMap<&'a str, Vec<&'a CommandEntry>> {
    let mut out: BTreeMap<&str, Vec<&CommandEntry>> = BTreeMap::new();
    for entry in &schema.commands {
        if header.includes(&entry.service) {
            out.entry(entry.service.as_str()).or_default().push(entry);
        }
    }
    for entries in out.values_mut() {
        entries.sort_by(|a, b| a.name.cmp(&b.name));
    }
    out
}

fn render(app: &Command, schema: &Schema, header: &Header) -> Vec<GeneratedFile> {
    let grouped = by_service(schema, header);
    let body = render_body(app, schema, &grouped, header);

    let mut files = vec![
        GeneratedFile {
            path: PathBuf::from("SKILL.md"),
            contents: render_skill_md(&body, header),
        },
        GeneratedFile {
            path: PathBuf::from("AGENTS.md"),
            contents: render_agents_md(&body, header),
        },
    ];

    for (service, entries) in &grouped {
        let (title, description) = service_about(app, service);
        files.push(GeneratedFile {
            path: PathBuf::from("references").join(format!("{service}.md")),
            contents: render_service_reference(
                service,
                &title,
                description.as_deref(),
                entries,
                header,
            ),
        });
    }

    files
}

/// SKILL.md: frontmatter first, because the Agent Skills format requires the
/// `---` fence to be the very first bytes of the file, then the generated
/// header, then the shared prose.
fn render_skill_md(body: &str, header: &Header) -> String {
    let description = "Use the mapbox CLI to call Mapbox APIs — styles, tiles, static images, \
                       geocoding, tilesets, fonts and access tokens — and to authenticate, \
                       preview requests and read its output.";
    format!(
        "---\nname: {SKILL_NAME}\ndescription: \"{description}\"\n---\n\n{}\n\n{body}",
        header.comment()
    )
}

/// AGENTS.md: the same prose under a heading, for an agent that reads
/// `AGENTS.md` and knows nothing about skills.
///
/// The body is byte-identical to SKILL.md's — pinned by
/// `the_agents_md_and_skill_md_bodies_are_identical`, because two documents
/// that are supposed to say the same thing and are written twice say two
/// things within a month. Only the wrapper differs: the frontmatter is a
/// skill-loader's business, and the heading is what a plain Markdown reader
/// needs in its place.
fn render_agents_md(body: &str, header: &Header) -> String {
    format!("# mapbox CLI\n\n{}\n\n{body}", header.comment())
}

/// A service's summary and its longer description, off the built tree.
///
/// Read from clap rather than from the `ServiceSpec` so the four
/// hand-written groups — `auth`, `tilesets-cli`, `generate-skills` — are
/// described the same way the generated ones are, and so a service whose
/// about line is reworded in `build_app` is reworded here too.
fn service_about(app: &Command, service: &str) -> (String, Option<String>) {
    match app.find_subcommand(service) {
        Some(cmd) => (
            cmd.get_about().map(ToString::to_string).unwrap_or_default(),
            cmd.get_long_about().map(ToString::to_string),
        ),
        None => (String::new(), None),
    }
}

fn render_body(
    app: &Command,
    schema: &Schema,
    grouped: &BTreeMap<&str, Vec<&CommandEntry>>,
    header: &Header,
) -> String {
    let mut out = String::new();

    out.push_str(
        "## When to use this\n\n\
         Reach for `mapbox` whenever a task involves a Mapbox API: reading or writing \
         styles, fetching tiles or static images, geocoding, querying tilesets, \
         listing or inspecting access tokens. It is one binary, it needs no SDK, and \
         every command answers on stdout in a shape a program can read.\n\n\
         Do not hand-write a `curl` against `api.mapbox.com` when a command exists — \
         the command already knows the URL, the required parameters, the token and the \
         error shape. `mapbox --schema <command>` prints all of that as JSON if you \
         need to check before running.\n\n",
    );

    out.push_str("## The one-minute version\n\n```sh\n");
    for line in [
        "mapbox auth whoami",
        "mapbox styles list -u USERNAME",
        "mapbox --schema styles list",
    ] {
        out.push_str(line);
        out.push('\n');
    }
    out.push_str(
        "```\n\n\
         The first says which token the next command will use and whose it is. The \
         second runs a real request. The third describes a command without running \
         it, which is the cheapest way to learn what one takes.\n\n",
    );

    out.push_str("## Authentication\n\n");
    out.push_str(
        "Every command that makes a request needs an access token. The CLI sends it as \
         the `access_token` query parameter, so it is never one of the arguments listed \
         in a reference page. It is resolved from these, highest first:\n\n",
    );
    for (index, (_, prose)) in token_precedence().iter().enumerate() {
        out.push_str(&format!("{}. {prose}\n", index + 1));
    }
    out.push_str(
        "\nThe account a URL asks for is separate from the token: pass `--username`/`-u`, \
         set `MAPBOX_USERNAME`, or let a stored login supply it. A command whose URL has \
         an account placeholder cannot run without one.\n\n\
         `--use-login` removes step 2, and only step 2 — a `--token` typed on the command \
         line still wins. It is the flag to reach for when a token left in a shell profile \
         is shadowing a login for a different account.\n\n",
    );

    out.push_str("## The output contract\n\n");
    out.push_str(&format!(
        "stdout carries the result and nothing else. Warnings, progress and errors go to \
         stderr, so a pipe reads clean.\n\n\
         `--output`/`-o` takes `{auto}`, `{text}` or `{json}`, and defaults to `{auto}`: \
         text at a terminal, JSON when stdout is a pipe or a file. So a script gets JSON \
         without asking, and a person gets a table without asking. `{env}` sets the same \
         thing for a session.\n\n\
         Three things are exempt, and each for a reason worth knowing:\n\n\
         - A binary response — a tile, a static image, a font glyph range — is written to \
         stdout as bytes whatever `--output` says. Redirect it to a file.\n\
         - `--help` and `--version` are clap's own rendering, not a result.\n\
         - `mapbox {tilesets_cli}` forwards to another program, which has no equivalent option; \
         `--output` written before it earns a warning on stderr and changes nothing.\n\n\
         `--id <ID>` picks one row out of a command that returns a list, in either mode.\n\n",
        auto = output::AUTO,
        text = output::TEXT,
        json = output::JSON,
        env = output::ENV,
        tilesets_cli = tilesets_cli::COMMAND,
    ));

    out.push_str("## Errors\n\n");
    out.push_str(
        "A failure exits non-zero and writes to stderr. Under `json` it is one object with \
         a machine-readable `code`, a `message`, and `status` when the failure came from an \
         HTTP response — so a caller can branch on the code rather than parsing prose. \
         Under `text` it is the message, plus a tip where there is one to give.\n\n\
         Two codes are worth special-casing: `missing_subcommand` means the command line \
         named a command group but no operation, and an HTTP `401` means the token is the \
         problem — the message says which of the sources above supplied it.\n\n",
    );

    out.push_str("## Dry runs\n\n");
    out.push_str(&format!(
        "Every command that changes something takes `--{dry}`: it prints the request it \
         would send, or the file it would change, and exits without doing it. Commands \
         that only read do not have the flag, so its presence in a reference page's \
         argument table is itself the answer to whether a command mutates anything.\n\n\
         Use it before any destructive command you have not run before. It costs nothing \
         and it is the only way to see the resolved URL without spending the request.\n\n",
        dry = executor::DRY_RUN_ARG,
    ));

    out.push_str("## Describing a command as JSON\n\n");
    out.push_str(&format!(
        "`mapbox --{schema_arg} <command>` prints the full description of a command as \
         JSON: every argument with its type, whether it is required, the values it \
         accepts, where it lands in the request, and the method and URL template. It \
         works at every level — `mapbox --{schema_arg}` for the whole CLI, \
         `mapbox --{schema_arg} styles` for one service, `mapbox --{schema_arg} styles \
         list` for one command — and needs no token, because it makes no request.\n\n\
         Prefer it over `--help` when a program is choosing the arguments. The reference \
         pages here shorten a description that will not fit a table cell; \
         `--{schema_arg}` has the whole of every one.\n\n",
        schema_arg = schema::ARG,
    ));

    out.push_str(&format!(
        "## `mapbox {}` is a proxy\n\n",
        tilesets_cli::COMMAND
    ));
    out.push_str(&format!(
        "`mapbox {cmd}` forwards everything after the subcommand name, verbatim, to the \
         separately-installed `{binary}` binary from the Python package `mapbox-tilesets`. \
         Two consequences that catch everyone:\n\n\
         - A `mapbox` global written *after* `{cmd}` goes to the child, which has never \
         heard of it. Write globals before the subcommand name: \
         `mapbox --{schema_arg} {cmd}`, not `mapbox {cmd} --{schema_arg}`.\n\
         - `mapbox {cmd} --help` shows the child's help, not this CLI's.\n\n\
         Its token is resolved as above and passed in the child's environment rather than \
         its argv, so it never appears in `ps`. A `--token` written after `{cmd}` is \
         forwarded and wins, which is the documented way to use a different token for one \
         call. `--use-login` is the mirror image: it makes a stored login outrank a token \
         already exported in the shell — worth knowing, because the Tilesets API answers a \
         wrong-account token with a bare `Not found` that points nowhere near the cause.\n\n",
        cmd = tilesets_cli::COMMAND,
        binary = tilesets_cli::DEFAULT_BINARY,
        schema_arg = schema::ARG,
    ));

    out.push_str("## Command groups\n\n");
    out.push_str("| Command group | Commands | What it covers | Reference |\n|---|---|---|---|\n");
    for (service, entries) in grouped {
        let (title, _) = service_about(app, service);
        out.push_str(&format!(
            "| `{service}` | {} | {} | [references/{service}.md](references/{service}.md) |\n",
            entries.len(),
            cell(crate::first_sentence(&title)),
        ));
    }
    out.push('\n');

    out.push_str("## Global options\n\n");
    out.push_str(
        "Accepted by every command, in any position — except after \
         `mapbox tilesets-cli`, per the section above.\n\n",
    );
    out.push_str("| Option | Type | Values | Default | Environment | Description |\n|---|---|---|---|---|---|\n");
    let mut globals: Vec<&Argument> = schema.global_options.iter().collect();
    globals.sort_by_key(|arg| spelling(arg));
    for arg in globals {
        out.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} |\n",
            written_cell(arg),
            arg.value_type,
            values_cell(arg),
            arg.default.as_deref().map(code).unwrap_or_default(),
            arg.env.as_deref().map(code).unwrap_or_default(),
            describe(arg),
        ));
    }
    out.push('\n');

    out.push_str(&format!(
        "---\n\nThis skill was generated from the command tree of `{SKILL_NAME}` \
         {}. Regenerate it with `mapbox generate-skills` after upgrading the CLI; \
         do not edit it by hand.\n",
        header.cli_version,
    ));

    out
}

/// One service's commands, in full.
fn render_service_reference(
    service: &str,
    title: &str,
    description: Option<&str>,
    entries: &[&CommandEntry],
    header: &Header,
) -> String {
    let mut out = format!("{}\n\n# mapbox {service}\n\n", header.comment());

    // A hand-written leaf is its own service — `generate-skills`, the proxy —
    // so the page heading, the service's about line and the one command's
    // summary are three copies of one sentence. The command's own block has
    // to stay, because that is the `###` heading every command is found by,
    // so the service-level intro is what gives way.
    let echoes = entries.len() == 1
        && entries[0].name == service
        && entries[0].summary.trim() == title.trim();

    if !echoes {
        if !title.is_empty() {
            out.push_str(&format!("{}\n\n", demote_headings(title)));
        }
        if let Some(description) = description.filter(|text| !text.trim().is_empty()) {
            out.push_str(&format!("{}\n\n", demote_headings(description.trim())));
        }
    }

    out.push_str(&format!(
        "{} command{}. A description too long for its table cell is shortened here; \
         `mapbox --{schema_arg} <command>` has the whole of every one, as JSON. \
         Placeholders in the examples are written in `UPPER_CASE` and have to be \
         replaced.\n\n## Commands\n\n",
        entries.len(),
        if entries.len() == 1 { "" } else { "s" },
        schema_arg = schema::ARG,
    ));

    for entry in entries {
        out.push_str(&format!("### {}\n\n", entry.command));

        if !entry.summary.trim().is_empty() {
            out.push_str(&format!("{}\n\n", demote_headings(entry.summary.trim())));
        }
        if let Some(description) = entry
            .description
            .as_deref()
            .filter(|text| !text.trim().is_empty())
        {
            out.push_str(&format!("{}\n\n", demote_headings(description.trim())));
        }

        if let Some(request) = &entry.request {
            out.push_str(&format!("`{} {}`\n\n", request.method, request.url));
        }
        if let Some(forwards_to) = entry.forwards_to {
            out.push_str(&format!("Forwards to the `{forwards_to}` binary.\n\n"));
        }
        if let Some(note) = entry.note {
            out.push_str(&format!("{note}\n\n"));
        }

        out.push_str(&arguments_table(entry));

        if let Some(detail) = &entry.detail_command {
            out.push_str(&format!(
                "To fetch one of the things this returns, see `{detail}`.\n\n"
            ));
        }

        out.push_str(&format!("```sh\n{}\n```\n\n", example_line(entry)));
    }

    out
}

/// An entry's arguments, in the order a caller writes them.
///
/// Positionals keep clap's declared order, because that order *is* how they
/// are identified — sorting them would describe a different command. Flags
/// have no order, so they are sorted by their long spelling: a table whose
/// rows move when an unrelated parameter is added is a table nobody can diff.
fn ordered_arguments(entry: &CommandEntry) -> Vec<&Argument> {
    let mut out: Vec<&Argument> = entry
        .arguments
        .iter()
        .filter(|arg| arg.kind == ArgKind::Positional)
        .collect();

    let mut flags: Vec<&Argument> = entry
        .arguments
        .iter()
        .filter(|arg| arg.kind != ArgKind::Positional)
        .collect();
    flags.sort_by_key(|arg| spelling(arg));

    out.extend(flags);
    out
}

fn arguments_table(entry: &CommandEntry) -> String {
    let arguments = ordered_arguments(entry);
    if arguments.is_empty() {
        return "Takes no arguments of its own.\n\n".to_string();
    }

    let mut out = String::from(
        "| Argument | Written as | Required | Type | Values | Description |\n\
         |---|---|---|---|---|---|\n",
    );
    for arg in arguments {
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | {} | {} |\n",
            arg.name,
            written_cell(arg),
            required_cell(arg),
            arg.value_type,
            values_cell(arg),
            describe(arg),
        ));
    }
    out.push('\n');
    out
}

/// The long flag, or the name for a positional. The sort key for anything
/// that has no inherent order.
fn spelling(arg: &Argument) -> String {
    arg.flag.clone().unwrap_or_else(|| arg.name.clone())
}

/// How the argument is typed on the command line, with its value shown as
/// something to replace.
fn written_as(arg: &Argument) -> String {
    match arg.kind {
        ArgKind::Positional => value_name(arg),
        ArgKind::Flag => spelling(arg),
        ArgKind::Option => format!("{} {}", spelling(arg), value_name(arg)),
    }
}

/// The same, as a table cell: the short spelling beside the long one, and a
/// note where the argument is one the command does not declare.
///
/// The short matters more than it looks. `-u` is how everyone writes
/// `--username`, and an agent that has only ever seen the long form will
/// read `-u` in someone's script as an unknown flag.
fn written_cell(arg: &Argument) -> String {
    let mut parts = vec![code(&written_as(arg))];
    if let Some(short) = &arg.short {
        parts.push(code(short));
    }
    if arg.source == Some("global") {
        parts.push("(global)".to_string());
    }
    parts.join(" ")
}

/// A value's name in a table: the argument's own, in the shape a reader
/// replaces.
///
/// Never a real accepted value. `--output auto` in a "written as" cell reads
/// as advice about what to pass rather than as a placeholder, and the Values
/// column already says which values there are. The examples are the other
/// way round — see [`placeholder`], which has to produce something the
/// parser accepts.
fn value_name(arg: &Argument) -> String {
    if arg.value_type == "path" {
        return "PATH".to_string();
    }
    // `uploadId` reads better as `UPLOAD_ID` than as `UPLOADID`, and the
    // specs spell parameters both ways.
    let mut out = String::new();
    let mut previous: Option<char> = None;
    for ch in arg.name.chars() {
        if ch.is_ascii_uppercase()
            && previous.is_some_and(|p| p.is_ascii_lowercase() || p.is_ascii_digit())
        {
            out.push('_');
        }
        out.push(if ch == '-' { '_' } else { ch });
        previous = Some(ch);
    }
    out.to_uppercase()
}

fn required_cell(arg: &Argument) -> String {
    if !arg.required_one_of.is_empty() {
        let flags: Vec<String> = arg
            .required_one_of
            .iter()
            .map(|name| format!("`--{name}`"))
            .collect();
        return format!("one of {}", flags.join(" / "));
    }
    if arg.required {
        "yes".to_string()
    } else {
        "no".to_string()
    }
}

/// At most a handful of accepted values, with a count for the rest.
///
/// Some spec enums run to dozens of languages or place types. Printing all of
/// them turns a reference page into a word list, and truncating without
/// saying so would make the table look like the whole truth — hence the
/// count and the pointer to `--schema`, which does publish all of them.
fn values_cell(arg: &Argument) -> String {
    const SHOWN: usize = 6;
    if arg.values.is_empty() {
        return String::new();
    }

    let shown: Vec<String> = arg
        .values
        .iter()
        .take(SHOWN)
        .map(|value| {
            if value.is_empty() {
                "`\"\"`".to_string()
            } else {
                code(value)
            }
        })
        .collect();

    let mut out = shown.join(", ");
    if arg.values.len() > SHOWN {
        out.push_str(&format!(" (+{} more)", arg.values.len() - SHOWN));
    }
    out
}

/// How much description one table cell will carry.
const CELL_BUDGET: usize = 220;

/// A description fit for a table cell, cut only where there is something to
/// cut.
///
/// Spec descriptions are paragraphs — `geocoder --types` alone is 4.6 KB —
/// and those are shortened to their first sentence, with `--schema` holding
/// the rest. A clap help string is not: it is already one line, written to
/// fit, and `crate::first_sentence` would cut `--output`'s at the `.` in
/// "Output format." and throw away everything that says what the formats
/// are. So the cut applies by length, to the text that would overflow.
fn summarise(text: &str) -> String {
    let whole = cell(text);
    if whole.len() <= CELL_BUDGET {
        return whole;
    }
    cell(crate::first_sentence(text))
}

/// The description, plus the handful of facts that would otherwise need a
/// column of their own.
///
/// Returns text that is already safe for a table cell, so a caller must not
/// escape it again — `cell` is not idempotent.
fn describe(arg: &Argument) -> String {
    let mut parts: Vec<String> = vec![];

    if let Some(description) = arg.description.as_deref() {
        let summary = summarise(description);
        if !summary.is_empty() {
            let ends_a_sentence = summary.ends_with('.') || summary.ends_with('!');
            parts.push(if ends_a_sentence {
                summary
            } else {
                format!("{summary}.")
            });
        }
    }
    if let Some(location) = arg.location {
        parts.push(format!("Sent in the request {location}."));
    }
    if let Some(content_type) = &arg.content_type {
        parts.push(format!("Sent as `{content_type}`."));
    }
    if let Some(field) = &arg.multipart_field {
        // `--file`'s own help already names the field on the multipart
        // operations, and saying it twice reads as a stutter.
        if !parts
            .iter()
            .any(|part| part.contains(&format!("`{field}`")))
        {
            parts.push(format!("Multipart field `{field}`."));
        }
    }
    // Several help strings already end with "repeatable", and "repeatable.
    // Repeatable." reads as a stutter rather than as emphasis.
    if arg.repeatable
        && !parts
            .iter()
            .any(|part| part.to_lowercase().contains("repeatable"))
    {
        parts.push("Repeatable.".to_string());
    }
    if arg.omit_with_empty {
        parts.push("Pass an empty string to leave it out of the URL.".to_string());
    }
    if !arg.conflicts_with.is_empty() {
        let others: Vec<String> = arg
            .conflicts_with
            .iter()
            .map(|name| format!("`--{name}`"))
            .collect();
        parts.push(format!("Cannot be given with {}.", others.join(" or ")));
    }
    if let Some(fills) = &arg.fills {
        parts.push(format!("Fills `{fills}` in the URL."));
    }

    parts.join(" ")
}

/// A ready-to-run invocation of one command: every argument it cannot do
/// without, and nothing it can.
///
/// Parseability is the hard requirement — `every_generated_example_parses`
/// hands each of these back to the very command tree it came from — so the
/// values respect each argument's declared enum and numeric type. Realism is
/// the soft one: where the argument accepts anything, the placeholder is its
/// own name in upper case, which reads as something to replace and cannot be
/// mistaken for a working value.
fn example_line(entry: &CommandEntry) -> String {
    // The proxy's own argument soaks up the child's whole command line, so
    // there is no argument here worth filling in. `--help` is both the
    // honest example and the first thing anyone should run.
    if entry.kind == Kind::Passthrough {
        return format!("{} --help", entry.command);
    }

    let mut words = vec![entry.command.clone()];

    // The globals a request cannot be built without go first, where a reader
    // is used to seeing them, and where they are visibly not part of the
    // command's own arguments.
    for arg in ordered_arguments(&entry_globals(entry)) {
        words.push(format!(
            "{} {}",
            spelling(arg),
            shell_word(&placeholder(arg))
        ));
    }

    let alternative = entry
        .arguments
        .iter()
        .filter_map(|arg| arg.required_one_of.first())
        .next()
        .cloned();

    for arg in ordered_arguments(entry) {
        if arg.source.is_some() {
            continue;
        }
        let needed = arg.required || Some(&arg.name) == alternative.as_ref();
        if !needed {
            continue;
        }
        match arg.kind {
            ArgKind::Positional => words.push(shell_word(&placeholder(arg))),
            ArgKind::Flag => words.push(spelling(arg)),
            ArgKind::Option => {
                words.push(spelling(arg));
                words.push(shell_word(&placeholder(arg)));
            }
        }
    }

    words.join(" ")
}

/// The entry's global arguments, wrapped so `ordered_arguments` can sort them
/// the same way it sorts everything else.
///
/// A borrow rather than a clone would need a second sorting helper for a
/// two-element list; this is the cheaper of the two.
fn entry_globals(entry: &CommandEntry) -> CommandEntry {
    CommandEntry {
        command: entry.command.clone(),
        service: entry.service.clone(),
        name: entry.name.clone(),
        kind: entry.kind,
        summary: String::new(),
        description: None,
        // Irrelevant here: this copy exists only to reuse the arguments'
        // sort, and nothing reads deprecation off it.
        deprecated: false,
        request: None,
        detail_command: None,
        forwards_to: None,
        note: None,
        aliases: vec![],
        arguments: entry
            .arguments
            .iter()
            .filter(|arg| arg.source == Some("global") && arg.required)
            .map(clone_argument)
            .collect(),
    }
}

fn clone_argument(arg: &Argument) -> Argument {
    Argument {
        name: arg.name.clone(),
        kind: arg.kind,
        flag: arg.flag.clone(),
        short: arg.short.clone(),
        required: arg.required,
        value_type: arg.value_type,
        values: arg.values.clone(),
        description: arg.description.clone(),
        repeatable: arg.repeatable,
        location: arg.location,
        source: arg.source,
        content_type: arg.content_type.clone(),
        multipart_field: arg.multipart_field.clone(),
        conflicts_with: arg.conflicts_with.clone(),
        required_one_of: arg.required_one_of.clone(),
        fills: arg.fills.clone(),
        omit_with_empty: arg.omit_with_empty,
        env: arg.env.clone(),
        default: arg.default.clone(),
    }
}

/// A value the argument will accept.
fn placeholder(arg: &Argument) -> String {
    // A declared enum leaves no choice: anything else is rejected by the
    // parser, so an example using a name placeholder would not run. Values
    // holding a single quote are skipped because `split_example` has no
    // escaping to express them — no bundled spec has one, and the example
    // test fails loudly if that ever changes.
    if let Some(value) = arg
        .values
        .iter()
        .find(|value| !value.is_empty() && !value.contains('\''))
    {
        return value.clone();
    }

    match arg.value_type {
        // Small, valid, and true of every numeric parameter the specs
        // declare: zoom, tile coordinates, longitudes, latitudes, limits.
        "integer" | "number" => "0".to_string(),
        _ if arg
            .content_type
            .as_deref()
            .is_some_and(|ct| ct.contains("json")) =>
        {
            "{}".to_string()
        }
        _ => value_name(arg),
    }
}

/// A value as one shell word, quoting only where it has to.
///
/// Single quotes and nothing else, matching [`split_example`] exactly. The
/// pair is the whole of this module's shell handling, and keeping it this
/// small is what makes the round trip checkable.
fn shell_word(value: &str) -> String {
    if value.is_empty() {
        return "''".to_string();
    }
    let plain = value
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || "._@/,:+=-".contains(c));
    if plain {
        value.to_string()
    } else {
        format!("'{value}'")
    }
}

/// A generated example split back into argv.
///
/// Understands single quotes and whitespace, and deliberately nothing else:
/// no double quotes, no backslash escapes, no variable expansion. That is
/// enough for everything [`shell_word`] can produce, and a parser that
/// handled more would be one that could disagree with the writer about a case
/// neither was tested on.
///
/// Only the tests read an example back — writing one is the command's job —
/// so this is compiled only for them.
#[cfg(test)]
fn split_example(line: &str) -> Vec<String> {
    let mut words = vec![];
    let mut current = String::new();
    let mut started = false;
    let mut quoted = false;

    for ch in line.chars() {
        match ch {
            '\'' => {
                quoted = !quoted;
                started = true;
            }
            c if c.is_whitespace() && !quoted => {
                if started {
                    words.push(std::mem::take(&mut current));
                    started = false;
                }
            }
            c => {
                current.push(c);
                started = true;
            }
        }
    }
    if started {
        words.push(current);
    }
    words
}

/// Spec prose, fitted underneath the heading it belongs to.
///
/// An OpenAPI `description` is Markdown, and the specs use it as such: the
/// geocoder's batch operation carries its own `### Example request` and
/// `### Response` headings, with a fenced `curl` block under each. Pasted
/// verbatim beneath a `###` command heading, those outrank the command they
/// describe — and one written at exactly `###` is indistinguishable from
/// another command's heading. That is not cosmetic: it is how
/// `every_command_appears_in_exactly_one_generated_file` reads the page, and
/// how an agent skimming for a command name reads it too.
///
/// So a heading in embedded prose is demoted to sit below the command's.
/// Lines inside a fenced block are left exactly as they are — a `#` there is
/// a shell comment or a colour, and rewriting one would corrupt the example
/// it belongs to.
fn demote_headings(text: &str) -> String {
    /// One level below the `###` a command heading uses.
    const UNDER: usize = 4;

    let mut out: Vec<String> = vec![];
    let mut fenced = false;

    for line in text.lines() {
        if line.trim_start().starts_with("```") {
            fenced = !fenced;
            out.push(line.to_string());
            continue;
        }

        let hashes = line.chars().take_while(|c| *c == '#').count();
        let heading = !fenced && hashes > 0 && hashes < UNDER && line[hashes..].starts_with(' ');
        if heading {
            out.push(format!("{}{}", "#".repeat(UNDER), &line[hashes..]));
        } else {
            out.push(line.to_string());
        }
    }

    out.join("\n")
}

/// Text fit for a Markdown table cell: no newlines, and no `|` that would end
/// the cell early.
fn cell(text: &str) -> String {
    let collapsed: String = text
        .split_whitespace()
        .collect::<Vec<&str>>()
        .join(" ")
        .replace('|', "\\|");
    collapsed
}

/// A value as inline code, with its own `|` escaped for the table around it.
fn code(text: &str) -> String {
    format!("`{}`", text.replace('|', "\\|"))
}

/// The token sources, in the order the CLI applies them, each with the prose
/// the skill publishes for it.
///
/// Written as a table keyed by [`crate::auth::TokenSource`] rather than as
/// three sentences, so `the_documented_token_precedence_is_the_resolvers`
/// can compare it against the resolver itself. Documentation of a precedence
/// that is not the precedence is worse than none: an agent that believes it
/// would debug the wrong token for an hour.
fn token_precedence() -> [(crate::auth::TokenSource, &'static str); 3] {
    use crate::auth::TokenSource;
    [
        (
            TokenSource::Flag,
            "`--token`/`-t`, typed on the command line. Outranks everything, including \
             `--use-login`.",
        ),
        (
            TokenSource::Environment,
            "`MAPBOX_ACCESS_TOKEN` in the environment. The legacy spelling \
             `MapboxAccessToken` is read only by `mapbox tilesets-cli`, which forwards to a \
             tool that accepts it. `--use-login` skips this step.",
        ),
        (
            TokenSource::Login,
            "Credentials stored by `mapbox auth login`, refreshed automatically when \
             stale. `--profile <NAME>` picks which set.",
        ),
    ]
}

/// A path relative to a skill directory, rendered with `/` regardless of the
/// host OS.
///
/// `GeneratedFile::path` and `strangers()`'s output are logical positions
/// inside the generated tree (`references/styles.md`), not filesystem paths
/// to hand to `std::fs` — those still go through `Path`/`PathBuf` untouched.
/// `Path::display()` uses the platform separator, so without this a Windows
/// build would report `references\styles.md` in text output and JSON alike:
/// a value that varies with the host OS in output the byte-identical and
/// dry-run tests pin, and a JSON string an agent would need to special-case
/// per platform to parse back into the paths this same command just wrote.
fn slashed(path: &Path) -> String {
    path.components()
        .map(|component| component.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

/// Decides what one destination's write would be, and refuses one that would
/// destroy something.
///
/// The skill directory is ours to replace only if every file in it says so.
/// One stranger — a note someone left, a file a later version of another tool
/// dropped in — and the whole directory is off limits, because there is no
/// way to tell "a file we no longer generate" from "a file that matters"
/// without asking. Naming the offenders is what makes `--force` a decision
/// rather than a reflex.
fn plan(destination: Destination, files: Vec<GeneratedFile>, force: bool) -> Result<Plan> {
    let plan = Plan { destination, files };

    if !force {
        let root = plan.skill_dir();
        let strangers = strangers(&root)?;
        if !strangers.is_empty() {
            let listed: Vec<String> = strangers
                .iter()
                .map(|path| format!("  {}", slashed(path)))
                .collect();
            return Err(CliError::new(
                "not_generated",
                format!(
                    "{} holds {} file{} `mapbox {COMMAND}` did not write:\n{}\nMove them \
                     elsewhere, or pass --force to replace the whole directory.",
                    root.display(),
                    strangers.len(),
                    if strangers.len() == 1 { "" } else { "s" },
                    listed.join("\n"),
                ),
            )
            .into());
        }
    }

    Ok(plan)
}

/// Every file under `root` that does not carry the generated marker, relative
/// to `root`. Empty for a directory that does not exist yet.
///
/// A file that cannot be read counts as a stranger, and so does a symlink:
/// both are cases where refusing costs a `--force` and proceeding could cost
/// someone's work.
fn strangers(root: &Path) -> Result<Vec<PathBuf>> {
    let mut out = vec![];
    if !root.exists() {
        return Ok(out);
    }

    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let entries =
            fs::read_dir(&dir).with_context(|| format!("Failed to read {}", dir.display()))?;
        for entry in entries {
            let entry = entry.with_context(|| format!("Failed to read {}", dir.display()))?;
            let path = entry.path();
            let file_type = entry
                .file_type()
                .with_context(|| format!("Failed to inspect {}", path.display()))?;

            if file_type.is_dir() {
                stack.push(path);
                continue;
            }
            if !marker_in(&fs::read(&path).unwrap_or_default()) {
                out.push(path.strip_prefix(root).unwrap_or(&path).to_path_buf());
            }
        }
    }

    out.sort();
    Ok(out)
}

/// Writes one plan, replacing the skill directory whole.
///
/// Built in a hidden sibling and renamed in, rather than written over the
/// existing tree, for two reasons. A crash halfway through an in-place write
/// leaves a skill that is half one version and half another, which an agent
/// will happily read. And a file we stopped generating would otherwise
/// survive forever, since nothing deletes it.
///
/// The old directory is moved aside rather than deleted first, so a failure
/// to rename the new one in can put it back.
fn apply(plan: &Plan) -> Result<()> {
    let root = plan.skill_dir();
    let parent = root
        .parent()
        .ok_or_else(|| anyhow!("{} has no parent directory", root.display()))?;

    fs::create_dir_all(parent).with_context(|| format!("Failed to create {}", parent.display()))?;

    let staging = parent.join(STAGING_DIR);
    let archive = parent.join(ARCHIVE_DIR);
    // Leftovers from a run that was killed between the renames below.
    let _ = fs::remove_dir_all(&staging);
    let _ = fs::remove_dir_all(&archive);

    write_tree(&staging, &plan.files)?;

    let existed = root.exists();
    if existed {
        fs::rename(&root, &archive).with_context(|| {
            format!(
                "Failed to move {} aside before replacing it",
                root.display()
            )
        })?;
    }

    if let Err(e) = fs::rename(&staging, &root) {
        if existed {
            let _ = fs::rename(&archive, &root);
        }
        let _ = fs::remove_dir_all(&staging);
        return Err(anyhow::Error::new(e).context(format!("Failed to write {}", root.display())));
    }

    if existed {
        let _ = fs::remove_dir_all(&archive);
    }
    Ok(())
}

/// The files, under a directory of their own.
///
/// `\n` line endings come from the rendering itself and are written as bytes,
/// so the same build produces the same files on every platform — a skill
/// generated on Windows and committed has to match one generated on Linux, or
/// the diff is noise.
fn write_tree(root: &Path, files: &[GeneratedFile]) -> Result<()> {
    for file in files {
        let path = root.join(&file.path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("Failed to create {}", parent.display()))?;
        }
        fs::write(&path, file.contents.as_bytes())
            .with_context(|| format!("Failed to write {}", path.display()))?;
    }
    Ok(())
}

/// What was written, or what would have been.
fn report(mode: Mode, plans: &[Plan], dry_run: bool) -> Result<()> {
    let mut lines: Vec<String> = vec![];
    if dry_run {
        lines.push("Dry run — nothing was written.".to_string());
    }

    for plan in plans {
        let count = plan.files.len();
        lines.push(format!(
            "{} {count} file{} under {}:",
            if dry_run { "Would write" } else { "Wrote" },
            if count == 1 { "" } else { "s" },
            Destination {
                root: plan.skill_dir(),
                source: plan.destination.source.clone(),
            },
        ));
        for file in &plan.files {
            lines.push(format!("  {}", slashed(&file.path)));
        }
    }

    let json = json!({
        "dry_run": dry_run,
        "skill": SKILL_NAME,
        "destinations": plans
            .iter()
            .map(|plan| json!({
                "root": plan.skill_dir().display().to_string(),
                "source": plan.destination.source,
                "files": plan
                    .files
                    .iter()
                    .map(|file| slashed(&file.path))
                    .collect::<Vec<String>>(),
            }))
            .collect::<Vec<serde_json::Value>>(),
    });

    output::emit(mode, &lines.join("\n"), json)
}

